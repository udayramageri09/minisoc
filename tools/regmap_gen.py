#!/usr/bin/env python3
"""Validate a MiniSoC platform spec (YAML) and generate regmap.h / regmap.tcl / regmap.md.

Usage: regmap_gen.py SPEC.yaml OUT_DIR
Exit code 0 on success, 1 on a spec error (message printed to stderr).
"""
from __future__ import annotations

import sys
from pathlib import Path

import yaml

VALID_ACCESS = {"RO", "WO", "RW", "W1C"}


class SpecError(Exception):
    """Raised when the platform specification is inconsistent."""


def _req(d: dict, key: str, where: str):
    if key not in d:
        raise SpecError(f"{where}: missing required key '{key}'")
    return d[key]


def validate(spec: dict) -> dict:
    """Check the spec and return a normalised copy. Raises SpecError on the first problem."""
    _req(spec, "platform", "spec")
    types = _req(spec, "peripheral_types", "spec")
    instances = _req(spec, "instances", "spec")
    memories = spec.get("memories", [])

    # --- register layouts per peripheral type ---
    for tname, t in types.items():
        regs = _req(t, "registers", f"type '{tname}'")
        names, offsets = set(), set()
        for r in regs:
            where = f"type '{tname}' register '{r.get('name', '?')}'"
            name, off, acc = _req(r, "name", where), _req(r, "offset", where), _req(r, "access", where)
            if name in names:
                raise SpecError(f"{where}: duplicate register name")
            if off in offsets:
                raise SpecError(f"{where}: duplicate offset {off:#x}")
            if off % 4:
                raise SpecError(f"{where}: offset {off:#x} is not 4-byte aligned")
            if acc not in VALID_ACCESS:
                raise SpecError(f"{where}: access '{acc}' not in {sorted(VALID_ACCESS)}")
            names.add(name)
            offsets.add(off)
            used = 0
            for f in r.get("fields", []):
                fw = f"{where} field '{f.get('name', '?')}'"
                lsb, width = _req(f, "lsb", fw), _req(f, "width", fw)
                if width < 1 or lsb < 0 or lsb + width > 32:
                    raise SpecError(f"{fw}: bits [{lsb + width - 1}:{lsb}] outside a 32-bit register")
                mask = ((1 << width) - 1) << lsb
                if used & mask:
                    raise SpecError(f"{fw}: overlaps another field")
                used |= mask

    # --- address map: every region must be disjoint (sort + check neighbours, O(n log n)) ---
    regions = []
    for m in memories:
        regions.append((m["base"], m["size"], m["name"]))
    irqs = {}
    for inst in instances:
        where = f"instance '{inst.get('name', '?')}'"
        tname = _req(inst, "type", where)
        if tname not in types:
            raise SpecError(f"{where}: unknown type '{tname}'")
        size = _req(inst, "size", where)
        max_off = max(r["offset"] for r in types[tname]["registers"])
        if max_off + 4 > size:
            raise SpecError(f"{where}: register at {max_off:#x} does not fit in size {size:#x}")
        if "irq" in inst:
            if inst["irq"] in irqs:
                raise SpecError(f"{where}: irq {inst['irq']} already used by {irqs[inst['irq']]}")
            irqs[inst["irq"]] = inst["name"]
        regions.append((_req(inst, "base", where), size, inst["name"]))

    names = [r[2] for r in regions]
    if len(set(names)) != len(names):
        raise SpecError("duplicate memory/instance name")
    regions.sort()
    for (b1, s1, n1), (b2, _s2, n2) in zip(regions, regions[1:]):
        if b1 + s1 > b2:
            raise SpecError(f"address overlap: {n1} [{b1:#x}+{s1:#x}) and {n2} at {b2:#x}")

    out = dict(spec)
    out["num_irqs"] = (max(irqs) + 1) if irqs else 0
    return out


def _field_macros(prefix: str, r: dict) -> list[str]:
    lines = []
    for f in r.get("fields", []):
        mask = ((1 << f["width"]) - 1) << f["lsb"]
        p = f"{prefix}_{r['name']}_{f['name']}"
        lines.append(f"#define {p}_POS {f['lsb']}u")
        lines.append(f"#define {p}_MSK 0x{mask:08X}u")
    return lines


def gen_header(spec: dict) -> str:
    L = ["/* AUTO-GENERATED by tools/regmap_gen.py from the platform YAML spec - DO NOT EDIT */",
         "#pragma once", "",
         f"#define MINISOC_BUS_LATENCY_NS {spec.get('bus_latency_ns', 0)}u",
         f"#define MINISOC_NUM_IRQS {spec['num_irqs']}u", ""]
    for m in spec.get("memories", []):
        L += [f"#define {m['name']}_BASE 0x{m['base']:08X}u",
              f"#define {m['name']}_SIZE 0x{m['size']:08X}u",
              f"#define {m['name']}_LATENCY_NS {m.get('latency_ns', 0)}u", ""]
    for tname, t in spec["peripheral_types"].items():
        P = tname.upper()
        L.append(f"/* ---- type {tname}: {t.get('desc', '')} ---- */")
        for r in t["registers"]:
            L.append(f"#define {P}_{r['name']}_OFF 0x{r['offset']:02X}u  /* {r['access']} */")
            L += _field_macros(P, r)
        L.append("")
    for inst in spec["instances"]:
        N = inst["name"]
        L += [f"/* ---- instance {N} ({inst['type']}) ---- */",
              f"#define {N}_BASE 0x{inst['base']:08X}u",
              f"#define {N}_SIZE 0x{inst['size']:08X}u"]
        if "irq" in inst:
            L.append(f"#define {N}_IRQ {inst['irq']}u")
        for r in spec["peripheral_types"][inst["type"]]["registers"]:
            L.append(f"#define {N}_{r['name']} ({N}_BASE + 0x{r['offset']:02X}u)")
        L.append("")
    return "\n".join(L) + "\n"


def gen_tcl(spec: dict) -> str:
    L = ["# AUTO-GENERATED by tools/regmap_gen.py - DO NOT EDIT"]
    for m in spec.get("memories", []):
        L += [f"set ::{m['name']}_BASE 0x{m['base']:08X}", f"set ::{m['name']}_SIZE 0x{m['size']:08X}"]
    for tname, t in spec["peripheral_types"].items():
        for r in t["registers"]:
            for f in r.get("fields", []):
                mask = ((1 << f["width"]) - 1) << f["lsb"]
                L.append(f"set ::{tname.upper()}_{r['name']}_{f['name']}_MSK 0x{mask:08X}")
    for inst in spec["instances"]:
        N = inst["name"]
        L.append(f"set ::{N}_BASE 0x{inst['base']:08X}")
        if "irq" in inst:
            L.append(f"set ::{N}_IRQ {inst['irq']}")
        for r in spec["peripheral_types"][inst["type"]]["registers"]:
            L.append(f"set ::{N}_{r['name']} 0x{inst['base'] + r['offset']:08X}")
    return "\n".join(L) + "\n"


def gen_markdown(spec: dict) -> str:
    L = [f"# {spec['platform']} register map", "", "_Generated from the YAML spec. Do not edit._", "",
         "| Region | Type | Base | Size | IRQ |", "|---|---|---|---|---|"]
    for m in spec.get("memories", []):
        L.append(f"| {m['name']} | memory | 0x{m['base']:08X} | 0x{m['size']:X} | - |")
    for i in spec["instances"]:
        L.append(f"| {i['name']} | {i['type']} | 0x{i['base']:08X} | 0x{i['size']:X} | {i.get('irq', '-')} |")
    for tname, t in spec["peripheral_types"].items():
        L += ["", f"## {tname}", "", t.get("desc", ""), "",
              "| Offset | Register | Access | Fields | Description |", "|---|---|---|---|---|"]
        for r in t["registers"]:
            fields = ", ".join(f"{f['name']}[{f['lsb'] + f['width'] - 1}:{f['lsb']}]" for f in r.get("fields", [])) or "-"
            L.append(f"| 0x{r['offset']:02X} | {r['name']} | {r['access']} | {fields} | {r.get('desc', '')} |")
    return "\n".join(L) + "\n"


def main(argv: list[str]) -> int:
    if len(argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    spec_path, out_dir = Path(argv[1]), Path(argv[2])
    try:
        spec = validate(yaml.safe_load(spec_path.read_text()))
    except SpecError as e:
        print(f"regmap_gen: spec error: {e}", file=sys.stderr)
        return 1
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "regmap.h").write_text(gen_header(spec))
    (out_dir / "regmap.tcl").write_text(gen_tcl(spec))
    (out_dir / "regmap.md").write_text(gen_markdown(spec))
    print(f"regmap_gen: wrote regmap.h/.tcl/.md to {out_dir}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
